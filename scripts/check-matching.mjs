import assert from 'node:assert/strict';
import fs from 'node:fs';
import {newProfile,fit,rank,eligible,nextDog,familyRanking,sanitizeProfile} from '../engine.mjs';
import {POPULATIONS,populationCount,POPULATION_BALANCE} from '../population.mjs';
import {populationBalance} from './population-model.mjs';
const dogs=JSON.parse(fs.readFileSync(new URL('../dogs.json',import.meta.url)));
const by=id=>dogs.find(d=>d.id===id),lab=by('labrador-retriever'),poodle=by('standard-poodle');
assert.equal(dogs.filter(b=>!b.variableTraits).length,67);
assert.equal(dogs.length,68);
assert.equal(new Set(dogs.map(d=>d.id)).size,68);
assert(dogs.every(b=>b.photo&&b.disadvantages.length&&b.facts.lifespan));
const player=newProfile('Ada');
assert.equal(Object.keys(POPULATIONS).length,dogs.length);
assert(dogs.every(b=>Number.isFinite(populationCount(b))&&populationCount(b)>0),'Every breed has a numerical estimate');
assert(Object.values(POPULATIONS).every(p=>p.low>0&&p.low<=p.estimate&&p.high>=p.estimate),'Scenario bounds must contain their estimate');
assert.deepEqual(rank(dogs,player).map(populationCount),dogs.map(populationCount).sort((a,b)=>b-a),'Default browsing follows estimated counts for every breed');
assert.equal(rank(dogs,player).length,dogs.length,'Population sorting keeps all breeds browsable');
const input=JSON.parse(fs.readFileSync(new URL('../data/population-inputs.json',import.meta.url)));
assert.equal(dogs.map(populationCount).reduce((s,n)=>s+n,0),POPULATION_BALANCE.catalog);
assert(POPULATION_BALANCE.withinRange&&POPULATION_BALANCE.unlisted>0,'The catalog must fit the worldwide benchmark and leave room for unlisted breeds');
assert.equal(POPULATION_BALANCE.catalog+POPULATION_BALANCE.unlisted,POPULATION_BALANCE.reference);
assert.equal(populationBalance(input,{...POPULATIONS,'singapore-special':{estimate:20000,includedIn:'mixed-breed-dogs'}}).catalog,POPULATION_BALANCE.catalog,'A regional subset cannot be counted twice');
player.top=lab.id;
assert.notEqual(nextDog(dogs,player).id,lab.id,'A dog cannot be its own challenger');
player.prefs=['lowShed','trainable','family'];
assert(fit(poodle,player)>fit(lab,player),'Stated low shedding should favor the Poodle over the Lab');
player.rules=['lowShed'];
assert.equal(eligible(lab,player),false);
assert(rank(dogs,player).every(d=>d.profile.shedding<=2),'Must-haves filter the full candidate list');
const first=nextDog(dogs,player);player.seen.push(first.id);
assert.notEqual(nextDog(dogs,player)?.id,first.id,'Passed challengers should not immediately repeat');
player.seen=dogs.map(d=>d.id);
assert.equal(nextDog(dogs,player),null,'Candidate exhaustion ends instead of looping');
const before=fit(lab,player);player.cute.push(lab.id);
assert.equal(fit(lab,player),before,'Cuteness must not silently infer lifestyle preferences');
const other=newProfile('Linus');other.top=lab.id;other.rules=['small'];
assert(familyRanking(dogs,[player,other]).every(x=>x.dog.size==='small'&&x.dog.profile.shedding<=2),'Family suggestions honor every person’s hard requirements');
other.prefs=['large'];player.prefs=['small'];
assert.deepEqual(familyRanking(dogs,[player,other]).map(x=>x.score),familyRanking(dogs,[other,player]).map(x=>x.score),'Family member order must not change scores');
const restored=sanitizeProfile({name:'Ada',top:'unknown',prefs:['fake','lowShed'],rules:['fake'],cute:['unknown'],rounds:-5,notes:{[lab.id]:'My favorite'}},new Set(dogs.map(b=>b.id)));
assert.equal(restored.top,null);assert.deepEqual(restored.prefs,['lowShed']);assert.equal(restored.rounds,0);assert.equal(restored.notes[lab.id],'My favorite');
console.log('Matching checks passed: 68 numerical population estimates, sorting, exclusions, no repeats, appearance separation, family fairness, storage validation.');
