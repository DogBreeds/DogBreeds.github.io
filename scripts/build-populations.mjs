import fs from 'node:fs';
import {estimatePopulations,populationBalance} from './population-model.mjs';
const input=JSON.parse(fs.readFileSync(new URL('../data/population-inputs.json',import.meta.url)));
const dogs=JSON.parse(fs.readFileSync(new URL('../dogs.json',import.meta.url)));
const estimates=estimatePopulations(input,dogs);
const balance=populationBalance(input,estimates);
if(!balance.withinRange||balance.unlisted<0)throw Error('Population estimates fall outside the worldwide budget; review assumptions before publishing.');
const output=`// Generated by scripts/build-populations.mjs. Rough scenarios, not census counts.\nexport const POPULATIONS=${JSON.stringify(estimates,null,1)};\nexport const POPULATION_BALANCE=${JSON.stringify(balance,null,1)};\nexport const population=b=>POPULATIONS[typeof b==='string'?b:b.id];\nexport const populationCount=b=>population(b)?.estimate??0;\nexport const formatPopulation=n=>new Intl.NumberFormat('en',{notation:'compact',maximumSignificantDigits:2}).format(n);\n`;
const destination=new URL('../population.mjs',import.meta.url);
if(process.argv.includes('--check')){
 if(fs.readFileSync(destination,'utf8')!==output)throw Error('Population output is stale; run node scripts/build-populations.mjs');
 console.log('All population estimates reproduce from saved inputs.');
}else{
 fs.writeFileSync(destination,output);
 fs.copyFileSync(new URL('../data/population-inputs.json',import.meta.url),new URL('../population-inputs.json',import.meta.url));
 fs.copyFileSync(new URL('../docs/breed-population-research.md',import.meta.url),new URL('../population-method.md',import.meta.url));
 console.log(`Built ${dogs.length} worldwide population estimates.`);
}
